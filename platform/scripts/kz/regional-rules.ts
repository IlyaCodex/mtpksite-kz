const SPACE = '((?:\\s|&nbsp;| )+)';
const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function compile(from: string, to: string): (s: string) => string {
  const words = from.split(' ').map(escape);
  const re = new RegExp(`(?<![\\p{L}\\p{N}])${words.join(SPACE)}(?![\\p{L}\\p{N}])`, 'gu');
  const target = to.split(' ');
  return (s) =>
    s.replace(re, (...args) => {
      const gaps = args.slice(1, words.length) as string[];
      return target.reduce((out, word, i) => (i === 0 ? word : out + (gaps[i - 1] ?? ' ') + word), '');
    });
}

const upper = (s: string) => s[0]!.toUpperCase() + s.slice(1);
const COMPILED = [...RULES]
  .sort((a, b) => b[0].length - a[0].length)
  .flatMap(([from, to]) => (from[0] === from[0]!.toLowerCase() ? [compile(from, to), compile(upper(from), upper(to))] : [compile(from, to)]));

